static const size_t GLYPH_SOURCE_COUNT = sizeof(GLYPH_SOURCE) / sizeof(GLYPH_SOURCE[0]);

// Indexed directly by (uint8_t)character; zero-initialized, so anything not
// in GLYPH_SOURCE is a blank glyph by default (which also covers space).
static uint16_t glyph_table[128][FONT_GLYPH_WIDTH];

// Transposes Spleen's row-major bytes (bit7 = leftmost column) into the
// column-major format set_coil_state() expects (bit15 = top row = COIL1).
static void convert_glyph(const uint8_t rows[FONT_HEIGHT], uint16_t out[FONT_GLYPH_WIDTH]) {
  for (int col = 0; col < FONT_GLYPH_WIDTH; col++) {
    uint16_t bits = 0;
    for (int row = 0; row < FONT_HEIGHT; row++) {
      if (rows[row] & (0x80 >> col)) {
        bits |= (uint16_t)0x8000 >> row;
      }
    }
    out[col] = bits;
  }
}

void font_init() {
  for (size_t i = 0; i < GLYPH_SOURCE_COUNT; i++) {
    const GlyphSource &g = GLYPH_SOURCE[i];
    convert_glyph(g.rows, glyph_table[(uint8_t)g.ch]);
  }
}

void font_get_glyph(char c, uint16_t *out) {
  uint8_t idx = (uint8_t)toupper((unsigned char)c);
  const uint16_t *g = (idx < 128) ? glyph_table[idx] : glyph_table[(uint8_t)' '];
  memcpy(out, g, sizeof(uint16_t) * FONT_GLYPH_WIDTH);
}

void font_print_ascii(char c) {
  uint16_t cols[FONT_GLYPH_WIDTH];
  font_get_glyph(c, cols);

  for (int row = 0; row < FONT_HEIGHT; row++) {
    char line[FONT_GLYPH_WIDTH + 1];
    for (int col = 0; col < FONT_GLYPH_WIDTH; col++) {
      line[col] = (cols[col] & ((uint16_t)0x8000 >> row)) ? '#' : '.';
    }
    line[FONT_GLYPH_WIDTH] = '\0';
    log_i("%s", line);
  }
}
