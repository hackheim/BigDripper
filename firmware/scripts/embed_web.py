"""PlatformIO pre-build script: embeds the web UI (firmware/web/) in the
firmware.

Every file in web/ is gzipped into src/generated/web_assets.h as a byte
array, with its URL path, content type and an ETag, for web.cpp to serve
with Content-Encoding: gzip. Only rewritten when something changed, so an
unchanged UI doesn't trigger a recompile.

Also runs on its own: python3 scripts/embed_web.py (from firmware/).
"""

import gzip
import hashlib
import os

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".wasm": "application/wasm",
}
# Not served: documentation and local development helpers.
SKIP = {".md", ".py"}


def embed(project_dir):
    web_dir = os.path.join(project_dir, "web")
    out_dir = os.path.join(project_dir, "src", "generated")
    out_path = os.path.join(out_dir, "web_assets.h")

    files = []
    for root, _, names in os.walk(web_dir):
        for name in sorted(names):
            ext = os.path.splitext(name)[1]
            if ext in SKIP or name.startswith("."):
                continue
            if ext not in MIME:
                raise SystemExit("embed_web.py: no content type for web/%s" % name)
            path = os.path.join(root, name)
            files.append((path, "/" + os.path.relpath(path, web_dir).replace(os.sep, "/"), MIME[ext]))
    files.sort(key=lambda f: f[1])

    lines = [
        "// Generated by scripts/embed_web.py from web/. Don't edit.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char *path;",
        "  const char *content_type;",
        "  const char *etag;",
        "  const uint8_t *gz;",
        "  size_t gz_len;",
        "};",
        "",
    ]
    table = []
    for i, (path, url, mime) in enumerate(files):
        with open(path, "rb") as f:
            raw = f.read()
        # mtime=0 so the same input always gives the same bytes.
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        etag = '"%s"' % hashlib.sha1(raw).hexdigest()[:16]
        lines.append("// %s: %d bytes, %d gzipped" % (url, len(raw), len(gz)))
        lines.append("static const uint8_t WEB_ASSET_%d[] = {" % i)
        for j in range(0, len(gz), 20):
            lines.append("  " + ",".join(str(b) for b in gz[j : j + 20]) + ",")
        lines.append("};")
        table.append('  {"%s", "%s", %s, WEB_ASSET_%d, sizeof(WEB_ASSET_%d)},'
                     % (url, mime, '"\\"%s\\""' % etag.strip('"'), i, i))
    lines.append("")
    lines.append("static const WebAsset WEB_ASSETS[] = {")
    lines += table
    lines.append("};")
    lines.append("static const size_t WEB_ASSET_COUNT = %d;" % len(files))
    text = "\n".join(lines) + "\n"

    os.makedirs(out_dir, exist_ok=True)
    old = None
    if os.path.exists(out_path):
        with open(out_path) as f:
            old = f.read()
    if old != text:
        with open(out_path, "w") as f:
            f.write(text)
        print("embed_web.py: wrote src/generated/web_assets.h (%d files)" % len(files))


try:
    Import("env")  # noqa: F821 -- provided by PlatformIO
    embed(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    embed(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
